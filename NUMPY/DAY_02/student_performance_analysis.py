import numpy as np
marks = np.array([85, 72, 90, 65, 78, 90, 55, 80])
print("Total Marks:", np.sum(marks))
print("Average Marks:", np.mean(marks))
print("Highest Mark:", np.max(marks))
print("Lowest Mark:", np.min(marks))
print("Index of Highest Mark:", np.argmax(marks))
print("Unique Marks:", np.unique(marks))
sorted_marks = np.sort(marks)
print("Sorted Marks:", sorted_marks)
reshaped = sorted_marks.reshape(2, 4)
print("\nReshaped Matrix:")
print(reshaped)
grace_marks = marks + 5
print("\nGrace Marks:", grace_marks)
split_arrays = np.split(reshaped, 2)
print("\nSplit Arrays:")
print(split_arrays)
shuffled = np.random.permutation(marks)
print("\nShuffled Copy:", shuffled)
print("Original Marks:", marks)

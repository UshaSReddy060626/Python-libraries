import cv2
image = cv2.imread("OPENCV/DAY_11/sample.jpeg")
gray = cv2.imread("OPENCV/DAY_11/sample.jpeg", 0)
cv2.imshow("Color Image", image)
cv2.imshow("Grayscale Image", gray)
cv2.imwrite("OPENCV/DAY_11/gray_image.jpeg", gray)
print("Shape:", image.shape)
print("Size:", image.size)
print("Data Type:", image.dtype)
resized = cv2.resize(image, (500, 400))
cv2.imshow("Resized Image", resized)
cropped = image[0:200, 0:200]
cv2.imshow("Cropped Image", cropped)
roi = image[10:150, 10:150]
cv2.imshow("ROI", roi)
cv2.line(image, (20, 20), (300, 20), (255, 0, 0), 2)
cv2.rectangle(image, (50, 50), (250, 200), (0, 255, 0), 2)
cv2.circle(image, (150, 150), 50, (0, 0, 255), 2)
cv2.putText(image,"OpenCV",(50, 240),cv2.FONT_HERSHEY_SIMPLEX,1,(255, 255, 255),2)
cv2.imshow("Drawing on Image", image)
gray_image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
cv2.imshow("BGR to Gray", gray_image)
rgb_image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
cv2.imshow("BGR to RGB", rgb_image)
cv2.waitKey(0)
cv2.destroyAllWindows()

import pandas as pd
data = {
    "Name": ["Rahul", "Priya", "Ankit", "Neha", "Rahul"],
    "Marks": [90, 75, None, 85, 90],
    "City": ["Delhi", "Mumbai", "Delhi", "Chennai", "Delhi"]
}
df = pd.DataFrame(data)
print("Original DataFrame")
print(df)
print("Shape:")
print(df.shape)
print("Info:")
df.info()
print("Description:")
print(df.describe())
print("Data Types:")
print(df.dtypes)
print("Columns:")
print(df.columns)
print("Index:")
print(df.index)
print("Select Name Column:")
print(df["Name"])
print("Select Name and Marks:")
print(df[["Name", "Marks"]])
print("First Row using iloc:")
print(df.iloc[0])
print("Rows with loc:")
print(df.loc[1:3])
print("Marks greater than 80:")
print(df[df["Marks"] > 80])
print("Students Rahul and Neha:")
print(df[df["Name"].isin(["Rahul", "Neha"])])
print("First 3 Rows:")
print(df.head(3))
print("Last 2 Rows:")
print(df.tail(2))
print("City Count:")
print(df["City"].value_counts())
print("Unique Cities:")
print(df["City"].unique())
print("Number of Unique Cities:")
print(df["City"].nunique())
print("Missing Values:")
print(df.isnull())
print("Fill Missing Marks with Average:")
df["Marks"] = df["Marks"].fillna(df["Marks"].mean())
print(df)
print("Replace Delhi with Bangalore:")
df["City"] = df["City"].replace("Delhi", "Bangalore")
print(df)
print("Remove Duplicate Rows:")
df = df.drop_duplicates()
print(df)
print("Convert Marks to Integer:")
df["Marks"] = df["Marks"].astype(int)
print(df)
print("Sort by Marks:")
print(df.sort_values(by="Marks"))
print("Sort by Index:")
print(df.sort_index())
df.to_csv("students.csv", index=False)
new_df = pd.read_csv("students.csv")
print("Read CSV:")
print(new_df)
df.to_excel("students.xlsx", index=False)
excel_df = pd.read_excel("students.xlsx")
print("Read Excel:")
print(excel_df)